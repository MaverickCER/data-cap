// Renders a committed results.json into a human-readable RESULTS.md.
// Current-snapshot only -- no comparison, no history, no regression
// language. That's render-benchmark-summary.mjs's job, run separately by CI.

function isDurationStats(value) {
  return (
    value &&
    typeof value === "object" &&
    typeof value.medianMs === "number" &&
    typeof value.iterations === "number"
  )
}

function renderDurationStats(stats) {
  return `median **${stats.medianMs.toFixed(2)}ms** (min ${stats.minMs.toFixed(2)}, p95 ${stats.p95Ms.toFixed(2)}, max ${stats.maxMs.toFixed(2)}, stdDev ${stats.stdDevMs.toFixed(2)}, n=${stats.iterations})`
}

function renderValue(value, depth) {
  if (isDurationStats(value)) return renderDurationStats(value)
  if (value && typeof value === "object" && !Array.isArray(value)) {
    const lines = []
    for (const [k, v] of Object.entries(value)) {
      lines.push(`${"  ".repeat(depth)}- **${k}**: ${renderValue(v, depth + 1)}`)
    }
    return "\n" + lines.join("\n")
  }
  if (Array.isArray(value))
    return value.length === 0 ? "(none)" : `${value.length} entr${value.length === 1 ? "y" : "ies"}`
  return String(value)
}

function renderTierEntry(entry) {
  const lines = [`- **id**: \`${entry.id}\``, `- **status**: ${entry.status}`]
  if (entry.status === "failed") {
    lines.push(`- **error**: ${entry.error?.name}: ${entry.error?.message}`)
    return lines.join("\n")
  }
  if (entry.status === "skipped") {
    lines.push(`- **reason**: ${entry.reason}`)
    return lines.join("\n")
  }
  for (const [key, value] of Object.entries(entry)) {
    if (key === "id" || key === "status") continue
    lines.push(`- **${key}**: ${renderValue(value, 1)}`)
  }
  return lines.join("\n")
}

function renderMetadataSection(metadata) {
  const lines = ["## Environment", ""]
  lines.push(
    `- Generated: \`${metadata.timing.startedAtUtc}\` → \`${metadata.timing.finishedAtUtc}\` (${metadata.timing.totalSuiteDurationMs}ms total)`,
  )
  lines.push(
    `- Node ${metadata.environment.nodeVersion} on ${metadata.environment.platform}/${metadata.environment.processArch}, ${metadata.environment.logicalCores} logical core(s)${metadata.environment.physicalCores ? ` (${metadata.environment.physicalCores} physical)` : ""}`,
  )
  lines.push(`- CPU: ${metadata.environment.cpuModel ?? "unknown"}`)
  lines.push(
    `- data-cap \`${metadata.versions.dataCapVersion}\`, benchmark suite \`s${metadata.versions.benchmarkSuiteVersion}\`, schema \`v${metadata.versions.benchmarkSchemaVersion}\`, tool \`${metadata.versions.benchmarkToolVersion}\``,
  )
  lines.push(
    `- git \`${metadata.git.gitCommit ?? "unknown"}\` on \`${metadata.git.gitBranch ?? "unknown"}\`${metadata.git.gitDirty ? " (dirty)" : ""}`,
  )
  lines.push(`- Generated by: \`${metadata.generatedBy}\``)
  lines.push("")
  return lines.join("\n")
}

export function renderResultsMarkdown(results, title) {
  const lines = [`# ${title}`, ""]
  lines.push(renderMetadataSection(results.metadata))

  const failedOrSkipped = []
  for (const [name, benchmark] of Object.entries(results.results)) {
    for (const [tier, entry] of Object.entries(benchmark.tiers)) {
      if (entry.status !== "completed") failedOrSkipped.push({ name, tier, ...entry })
    }
  }
  if (failedOrSkipped.length > 0) {
    lines.push("## Failed / skipped", "")
    for (const entry of failedOrSkipped) {
      lines.push(
        `- **${entry.name}.${entry.tier}**: ${entry.status}${entry.reason ? ` (${entry.reason})` : ""}${entry.error ? ` (${entry.error.name}: ${entry.error.message})` : ""}`,
      )
    }
    lines.push("")
  }

  for (const [name, benchmark] of Object.entries(results.results).sort(([a], [b]) =>
    a < b ? -1 : 1,
  )) {
    lines.push(`## \`${name}\``, "")
    for (const [tier, entry] of Object.entries(benchmark.tiers).sort(([a], [b]) =>
      a < b ? -1 : 1,
    )) {
      lines.push(`### ${tier}`, "")
      lines.push(renderTierEntry(entry))
      lines.push("")
    }
  }

  lines.push(
    "---",
    "",
    `_Rendered from \`results.json\` -- see [../README.md](../README.md) for methodology._`,
    "",
  )
  return lines.join("\n")
}
